    if args[:1] == ["fetch"] and len(args) == 4 and args[2] == "--dest":
        fetch(args[1], args[3])
    elif args == ["list"]:
        show_list()
    elif args == ["discover"]:
        discover()
    else:
        sys.exit(__doc__)
